import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import javax.tools.*;
import com.sun.source.tree.*;
import com.sun.source.util.JavacTask;

/** JDK 21 source launcher; parses sources only, never resolves or loads Eclipse classes. */
public class GenerateToolCatalog {
    static final String SOURCE = "plugins/plugin.eclipsectl.mcp.main/src/eclipsectlmcp/mcp/";
    static final String NOTICE = "<!-- Generated by scripts/GenerateToolCatalog.java. Do not edit. -->\n\n";
    record Param(String name, String type, String javaType, boolean required, String description) {}
    record Tool(String name, String type, String description, List<Param> params) {}
    record Server(String name, String version, String description, List<Tool> tools) {}
    record Schema(Map<String, String> types, Map<String, Object> defaults) {}

    public static void main(String[] args) {
        try {
            boolean check = false;
            Path root = Path.of(".");
            for (int i = 0; i < args.length; i++) {
                if (args[i].equals("--check")) check = true;
                else if (args[i].equals("--root") && i + 1 < args.length) root = Path.of(args[++i]);
                else throw new IllegalArgumentException("Usage: java scripts/GenerateToolCatalog.java [--check] [--root path]");
            }
            generate(root, check);
        } catch (Exception e) {
            System.err.println("Tool catalogue: " + e.getMessage());
            System.exit(1);
        }
    }

    static CompilationUnitTree parse(Path path) throws Exception {
        var compiler = ToolProvider.getSystemJavaCompiler();
        if (compiler == null) throw new IllegalStateException("JDK 21 or newer is required");
        var diagnostics = new DiagnosticCollector<JavaFileObject>();
        try (var files = compiler.getStandardFileManager(diagnostics, Locale.ROOT, StandardCharsets.UTF_8)) {
            var task = (JavacTask) compiler.getTask(null, files, diagnostics,
                    List.of("-proc:none", "--release", "21"), null, files.getJavaFileObjects(path));
            var unit = task.parse().iterator().next();
            for (var d : diagnostics.getDiagnostics())
                if (d.getKind() == Diagnostic.Kind.ERROR)
                    throw new IllegalArgumentException(path + ":" + d.getLineNumber() + ": " + d.getMessage(Locale.ROOT));
            return unit;
        }
    }

    static ClassTree declaration(Path path, String name) throws Exception {
        for (var tree : parse(path).getTypeDecls())
            if (tree instanceof ClassTree c && c.getSimpleName().contentEquals(name)) return c;
        throw new IllegalArgumentException("Missing class " + name + " in " + path);
    }

    static Object literal(Tree tree) {
        if (tree instanceof LiteralTree l && (l.getValue() instanceof String || l.getValue() instanceof Boolean))
            return l.getValue();
        if (tree instanceof ParenthesizedTree p) return literal(p.getExpression());
        if (tree instanceof BinaryTree b && b.getKind() == Tree.Kind.PLUS) {
            Object left = literal(b.getLeftOperand()), right = literal(b.getRightOperand());
            if (left instanceof String && right instanceof String) return (String) left + right;
        }
        throw new IllegalArgumentException("Unsupported annotation expression: " + tree);
    }

    static Schema schema(Path root, String name) throws Exception {
        var types = new LinkedHashMap<String, String>();
        var defaults = new LinkedHashMap<String, Object>();
        for (var member : declaration(root.resolve(SOURCE + "annotations/" + name + ".java"), name).getMembers()) {
            if (member instanceof MethodTree m) {
                String key = m.getName().toString(), type = m.getReturnType().toString();
                require(type.equals("String") || type.equals("boolean"), "Unsupported annotation type " + type);
                types.put(key, type);
                if (m.getDefaultValue() != null) defaults.put(key, literal(m.getDefaultValue()));
            }
        }
        return new Schema(types, defaults);
    }

    static Map<String, Object> annotation(ModifiersTree modifiers, String name, Schema schema) {
        Map<String, Object> found = null;
        for (var a : modifiers.getAnnotations()) {
            String type = a.getAnnotationType().toString();
            if (!type.equals(name) && !type.endsWith("." + name)) continue;
            require(found == null, "Duplicate @" + name);
            found = new LinkedHashMap<>(schema.defaults());
            var explicit = new HashSet<String>();
            for (var argument : a.getArguments()) {
                require(argument instanceof AssignmentTree, "Expected named argument in @" + name);
                var assignment = (AssignmentTree) argument;
                String key = assignment.getVariable().toString();
                require(schema.types().containsKey(key) && explicit.add(key), "Invalid/duplicate @" + name + " field " + key);
                Object value = literal(assignment.getExpression());
                require(schema.types().get(key).equals("String") ? value instanceof String : value instanceof Boolean,
                        "Wrong value type for @" + name + "." + key);
                found.put(key, value);
            }
            require(found.keySet().containsAll(schema.types().keySet()), "Missing required @" + name + " field");
        }
        return found;
    }

    static void require(boolean condition, String message) {
        if (!condition) throw new IllegalArgumentException(message);
    }

    static String string(Map<String, Object> values, String key) { return (String) values.get(key); }
    static String identifier(String value) {
        require(value != null && value.matches("[A-Za-z0-9_.-]+"), "Invalid/empty MCP name: " + value);
        return value;
    }

    static List<Server> catalog(Path root) throws Exception {
        Schema serverSchema = schema(root, "McpServer"), toolSchema = schema(root, "Tool"), paramSchema = schema(root, "ToolParam");
        var builtin = declaration(root.resolve(SOURCE + "McpServerBuiltins.java"), "McpServerBuiltins");
        var classes = new ArrayList<String>();
        for (var member : builtin.getMembers()) {
            if (member instanceof VariableTree v && v.getName().contentEquals("BUILT_IN_MCP_SERVERS")) {
                require(v.getInitializer() instanceof NewArrayTree, "Expected builtin class array");
                for (var value : ((NewArrayTree) v.getInitializer()).getInitializers()) {
                    require(value instanceof MemberSelectTree m && m.getIdentifier().contentEquals("class"), "Expected builtin class literal");
                    classes.add(((MemberSelectTree) value).getExpression().toString());
                }
            }
        }
        require(!classes.isEmpty(), "No builtin servers found");
        var servers = new TreeMap<String, Server>();
        var seenClasses = new HashSet<String>();
        for (String className : classes) {
            require(seenClasses.add(className), "Duplicate builtin " + className);
            var c = declaration(root.resolve(SOURCE + "servers/" + className + ".java"), className);
            require(c.getExtendsClause() == null && c.getImplementsClause().isEmpty(),
                    "Inherited server tools need explicit generator support: " + className);
            var s = annotation(c.getModifiers(), "McpServer", serverSchema);
            require(s != null, "Missing @McpServer: " + className);
            var tools = new TreeMap<String, Tool>();
            for (var member : c.getMembers()) {
                if (!(member instanceof MethodTree m)) continue;
                var t = annotation(m.getModifiers(), "Tool", toolSchema);
                if (t == null) continue;
                require(m.getModifiers().getFlags().contains(javax.lang.model.element.Modifier.PUBLIC),
                        "Tool must be public: " + className + "." + m.getName());
                var params = new ArrayList<Param>();
                var names = new HashSet<String>();
                for (var p : m.getParameters()) {
                    var a = annotation(p.getModifiers(), "ToolParam", paramSchema);
                    require(a != null, "Missing @ToolParam: " + className + "." + m.getName() + "." + p.getName());
                    String name = string(a, "name");
                    if (name.isBlank()) name = p.getName().toString();
                    require(names.add(identifier(name)), "Duplicate parameter " + name);
                    params.add(new Param(name, string(a, "type"), p.getType().toString(), (Boolean) a.get("required"), string(a, "description")));
                }
                String name = identifier(string(t, "name"));
                require(tools.putIfAbsent(name, new Tool(name, string(t, "type"), string(t, "description"), params)) == null,
                        "Duplicate tool " + className + "." + name);
            }
            String name = identifier(string(s, "name"));
            require(servers.putIfAbsent(name, new Server(name, string(s, "version"), string(s, "description"), List.copyOf(tools.values()))) == null,
                    "Duplicate server " + name);
        }
        return List.copyOf(servers.values());
    }

    static String md(String value) {
        return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                .replace("\\", "&#92;").replace("|", "&#124;").replace("`", "&#96;")
                .replace("*", "&#42;").replace("_", "&#95;").replace("[", "&#91;").replace("]", "&#93;")
                .replace("\r\n", "\n").replace("\r", "\n").replace("\n", "<br>");
    }

    static String replaceBlock(String text, String name, String content) {
        String start = "<!-- BEGIN GENERATED " + name + " -->", end = "<!-- END GENERATED " + name + " -->";
        int a = text.indexOf(start), b = text.indexOf(end);
        require(a >= 0 && b > a && text.indexOf(start, a + 1) < 0 && text.indexOf(end, b + 1) < 0,
                "Missing or duplicate README generated block: " + name);
        return text.substring(0, a) + start + "\n" + content + "\n" + end + text.substring(b + end.length());
    }

    static void generate(Path root, boolean check) throws Exception {
        var servers = catalog(root);
        int total = servers.stream().mapToInt(s -> s.tools().size()).sum();
        var output = new LinkedHashMap<Path, String>();
        var index = new StringBuilder(NOTICE + "# MCP tool catalogue\n\n" + total + " tools across " + servers.size() + " builtin servers.\n\n");
        index.append("Generated from `McpServerBuiltins`, `@McpServer`, `@Tool`, and `@ToolParam` with JDK 21, without Eclipse.\n")
             .append("Schema types and required flags below are the annotation values, including defaults. Java types are shown separately.\n")
             .append("Runtime argument defaults, when applicable, are described in the annotation text.\n\n")
             .append("| Server | Version | Tools | Description |\n| --- | --- | ---: | --- |\n");
        var summary = new StringBuilder("| Server | Tools |\n| --- | ---: |\n");
        for (var s : servers) {
            index.append("| [").append(s.name()).append("](mcp-tools/").append(s.name()).append(".md) | ").append(md(s.version())).append(" | ")
                    .append(s.tools().size()).append(" | ").append(md(s.description())).append(" |\n");
            summary.append("| [").append(s.name()).append("](docs/mcp-tools/").append(s.name()).append(".md) | ").append(s.tools().size()).append(" |\n");
            var page = new StringBuilder(NOTICE + "# " + s.name() + "\n\n[All servers](../mcp-tools.md)\n\nVersion: " + md(s.version()) + ". Tools: " + s.tools().size() + ".\n\n");
            if (!s.description().isEmpty()) page.append(md(s.description())).append("\n\n");
            for (var t : s.tools()) {
                page.append("## ").append(t.name()).append("\n\n").append(md(t.description())).append("\n\nInput schema type: ").append(md(t.type())).append(".\n\n");
                if (t.params().isEmpty()) page.append("No parameters.\n\n");
                else {
                    page.append("| Parameter | Schema type | Java type | Required | Description |\n| --- | --- | --- | --- | --- |\n");
                    for (var p : t.params()) page.append("| ").append(md(p.name())).append(" | ").append(md(p.type())).append(" | ").append(md(p.javaType()))
                            .append(" | ").append(p.required() ? "Yes" : "No").append(" | ").append(md(p.description())).append(" |\n");
                    page.append('\n');
                }
            }
            output.put(Path.of("docs/mcp-tools/" + s.name() + ".md"), page.toString().stripTrailing() + "\n");
        }
        output.put(Path.of("docs/mcp-tools.md"), index.toString());
        String readme = normalized(Files.readString(root.resolve("README.md")));
        readme = replaceBlock(readme, "MCP COUNT", "EclipseCtl MCP exposes **" + total + " MCP tools** across " + servers.size() + " main servers, allowing AI assistants to:");
        readme = replaceBlock(readme, "MCP SERVERS", summary.toString().stripTrailing());
        output.put(Path.of("README.md"), readme);
        var stale = new ArrayList<String>();
        Path directory = root.resolve("docs/mcp-tools");
        if (Files.isDirectory(directory)) try (var paths = Files.list(directory)) {
            for (Path path : paths.filter(p -> p.toString().endsWith(".md")).sorted().toList())
                if (!output.containsKey(root.relativize(path)) && normalized(Files.readString(path)).startsWith(NOTICE))
                    stale.add(root.relativize(path).toString() + " (obsolete; remove this generated file)");
        }
        for (var entry : output.entrySet()) {
            Path path = root.resolve(entry.getKey());
            boolean differs = !Files.exists(path) || !normalized(Files.readString(path)).equals(entry.getValue());
            if (differs && check) stale.add(entry.getKey().toString());
            else if (differs) {
                Files.createDirectories(path.getParent());
                Files.writeString(path, entry.getValue(), StandardCharsets.UTF_8);
            }
        }
        require(stale.isEmpty(), "Stale catalogue files: " + String.join(", ", stale) + ". Run java scripts/GenerateToolCatalog.java");
        System.out.println("Tool catalogue " + (check ? "verified" : "generated") + ": " + total + " tools, " + servers.size() + " servers.");
    }

    static String normalized(String text) { return text.replace("\r\n", "\n"); }
}
