import java.nio.file.*;
import java.util.*;

/** Isolated integration fixtures; run with java scripts/TestToolCatalog.java. */
public class TestToolCatalog {
    static final Path GENERATOR = Path.of("scripts/GenerateToolCatalog.java").toAbsolutePath();
    static final String SOURCE = "plugins/plugin.eclipsectl.mcp.main/src/eclipsectlmcp/mcp/";
    static final String SERVER = """
            @McpServer(name="fixture") class Fixture {
                @Tool(name="test", description="First | line\\n" + "quoted \\\"value\\\"")
                public String test(@ToolParam(description="required") String key,
                    @ToolParam(name="optional", description="optional", required=false, type="integer") Integer count) { return ""; }
            }
            """;

    public static void main(String[] args) throws Exception {
        Path root = Files.createTempDirectory("mcp-catalog-test-");
        try {
            fixture(root);
            run(root, false, true, null);
            String index = Files.readString(root.resolve("docs/mcp-tools.md"));
            String page = Files.readString(root.resolve("docs/mcp-tools/fixture.md"));
            require(index.contains("1 tools across 1 builtin servers"), "registry must exclude unregistered classes");
            require(page.contains("Version: 9.0") && page.contains("Input schema type: object"), "annotation defaults");
            require(page.contains("Multiline<br>server<br>"), "Java text block annotation");
            require(page.contains("First &#124; line<br>quoted \"value\""), "concatenation and escaped strings");
            require(page.contains("| key | string | String | Yes | required |"), "default name/type/required");
            require(page.contains("| optional | integer | Integer | No | optional |"), "explicit optional parameter");
            Map<String, byte[]> before = snapshot(root);
            run(root, false, true, null);
            Map<String, byte[]> after = snapshot(root);
            require(before.keySet().equals(after.keySet()), "deterministic file set");
            for (String key : before.keySet()) require(Arrays.equals(before.get(key), after.get(key)), "deterministic output: " + key);
            run(root, true, true, null);
            Files.writeString(root.resolve("docs/mcp-tools/fixture.md"), "stale");
            run(root, true, false, "Stale catalogue files");
            require(Files.readString(root.resolve("docs/mcp-tools/fixture.md")).equals("stale"), "check must not write");
            run(root, false, true, null);
            Files.writeString(root.resolve("docs/mcp-tools/obsolete.md"), "<!-- Generated by scripts/GenerateToolCatalog.java. Do not edit. -->\n\nobsolete");
            run(root, true, false, "obsolete; remove this generated file");
            Files.delete(root.resolve("docs/mcp-tools/obsolete.md"));
            Files.writeString(root.resolve("docs/mcp-tools/manual.md"), "Manual documentation");
            run(root, true, true, null);
            require(Files.readString(root.resolve("docs/mcp-tools/manual.md")).equals("Manual documentation"), "preserve manual files");
            for (String relative : List.of("README.md", "docs/mcp-tools.md", "docs/mcp-tools/fixture.md")) {
                Path path = root.resolve(relative);
                Files.writeString(path, Files.readString(path).replace("\n", "\r\n"));
            }
            run(root, true, true, null);
            write(root, SOURCE + "servers/Fixture.java", SERVER.replace("    @Tool(name=\"test\"", "    @Tool(name=\"test\", description=\"duplicate\") public String duplicate() { return \"\"; }\n    @Tool(name=\"test\""));
            run(root, true, false, "Duplicate tool");
            write(root, SOURCE + "servers/Fixture.java", SERVER.replace("required=false", "required=UNKNOWN"));
            run(root, true, false, "Unsupported annotation expression");
            write(root, SOURCE + "servers/Fixture.java", SERVER.replace("description=\"required\"", "invalid=\"required\""));
            run(root, true, false, "Invalid/duplicate @ToolParam field");
            write(root, SOURCE + "servers/Fixture.java", SERVER.replace("description=\"required\"", "name=\"required\""));
            run(root, true, false, "Missing required @ToolParam field");
            write(root, SOURCE + "servers/Fixture.java", SERVER.replace("name=\"optional\"", "name=\"key\""));
            run(root, true, false, "Duplicate parameter");
            write(root, SOURCE + "servers/Fixture.java", SERVER);
            write(root, SOURCE + "McpServerBuiltins.java", "class McpServerBuiltins { static Class<?>[] BUILT_IN_MCP_SERVERS = { Fixture.class, Fixture.class }; }");
            run(root, true, false, "Duplicate builtin");
            System.out.println("Tool catalogue fixtures passed (defaults, escaping, required/optional, deterministic generation, stale/read-only check, duplicates, invalid annotations).");
        } finally {
            // The only removed files are under the fresh temporary fixture directory.
            try (var paths = Files.walk(root)) {
                for (Path path : paths.sorted(Comparator.reverseOrder()).toList()) Files.delete(path);
            }
        }
    }

    static void fixture(Path root) throws Exception {
        write(root, "README.md", "Before\n<!-- BEGIN GENERATED MCP COUNT -->\nold\n<!-- END GENERATED MCP COUNT -->\nMiddle\n<!-- BEGIN GENERATED MCP SERVERS -->\nold\n<!-- END GENERATED MCP SERVERS -->\nAfter\n");
        write(root, SOURCE + "annotations/McpServer.java", "@interface McpServer { String name(); String version() default \"9.0\"; String description() default \"\"\"\nMultiline\nserver\n\"\"\"; }");
        write(root, SOURCE + "annotations/Tool.java", "@interface Tool { String name() default \"\"; String description(); String type() default \"object\"; }");
        write(root, SOURCE + "annotations/ToolParam.java", "@interface ToolParam { String name() default \"\"; String description(); boolean required() default true; String type() default \"string\"; }");
        write(root, SOURCE + "McpServerBuiltins.java", "class McpServerBuiltins { static Class<?>[] BUILT_IN_MCP_SERVERS = { Fixture.class }; }");
        write(root, SOURCE + "servers/Fixture.java", SERVER);
        write(root, SOURCE + "servers/Forgotten.java", "@McpServer(name=\"forgotten\") class Forgotten {}");
    }

    static void write(Path root, String relative, String text) throws Exception {
        Path path = root.resolve(relative);
        Files.createDirectories(path.getParent());
        Files.writeString(path, text);
    }

    static Map<String, byte[]> snapshot(Path root) throws Exception {
        var result = new TreeMap<String, byte[]>();
        try (var paths = Files.walk(root)) {
            for (Path p : paths.filter(Files::isRegularFile).toList()) result.put(root.relativize(p).toString(), Files.readAllBytes(p));
        }
        return result;
    }

    static void run(Path root, boolean check, boolean success, String expected) throws Exception {
        var command = new ArrayList<>(List.of(Path.of(System.getProperty("java.home"), "bin", "java").toString(), GENERATOR.toString(), "--root", root.toString()));
        if (check) command.add("--check");
        var process = new ProcessBuilder(command).redirectErrorStream(true).start();
        if (!process.waitFor(30, java.util.concurrent.TimeUnit.SECONDS)) {
            process.destroyForcibly();
            throw new AssertionError("Generator fixture exceeded 30 seconds: " + root);
        }
        String output = new String(process.getInputStream().readAllBytes(), java.nio.charset.StandardCharsets.UTF_8);
        int status = process.exitValue();
        require((status == 0) == success, "Unexpected exit " + status + ": " + output);
        if (expected != null) require(output.contains(expected), "Expected " + expected + ": " + output);
    }

    static void require(boolean condition, String message) {
        if (!condition) throw new AssertionError(message);
    }
}
